import sys



class Logger:
  def __init__(self):
    pass
  def critical(self, msg, exc_info=False):
    print(msg, file=sys.stderr)
  def info(self, msg, exc_info=False):
    print(msg, file=sys.stderr)
  def warning(self, msg, exc_info=False):
    print(msg, file=sys.stderr)
  def error(self, msg, exc_info=False):
    print(msg, file=sys.stderr)


logger = Logger()




















































































































































































































